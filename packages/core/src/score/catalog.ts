const CATALOG_BY_ID: ReadonlyMap<string, CheckDefinition> = new Map(
  SCORE_CATALOG.map((definition) => [definition.id, definition])
);

const CATALOG_INDEX: ReadonlyMap<string, number> = new Map(
  SCORE_CATALOG.map((definition, index) => [definition.id, index])
);

export function getCheckDefinition(id: string): CheckDefinition | undefined {
  return CATALOG_BY_ID.get(id);
}

/** Position in the catalog, used as the final tie-break when ranking fixes. */
export function catalogIndexOf(id: string): number {
  return CATALOG_INDEX.get(id) ?? Number.MAX_SAFE_INTEGER;
}

export function catalogChecksForTier(tier: CheckTier): CheckDefinition[] {
  return SCORE_CATALOG.filter((definition) => definition.tier === tier);
}

/** Checks implemented in this catalog version (zero extra fetches). */
export function implementedChecks(): CheckDefinition[] {
  return SCORE_CATALOG.filter((definition) => definition.availability === 'now');
}
